// Writes validationSet2.json (profiles + ResQ's current result for each)
// here and into the mobile app's test fixtures, so both repos test the same
// profiles. See validationSet2.js.
//
//   node validation/buildValidationSet2.js [path/to/resq_app]

import { writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { PROFILES, toHealthScreening, toDonorRow } from "./validationSet2.js";
import { classifyDonorRow } from "../src/utils/eligibilityClassifier.js";

const here = dirname(fileURLToPath(import.meta.url));
const appRepo = resolve(process.argv[2] ?? join(here, "../../../resq_app"));

const profiles = PROFILES.map((p) => {
  const fixture = { id: p.id, tests: p.tests, age: p.age, weightKg: p.weight, gender: p.sex, healthScreening: toHealthScreening(p) };
  const result = classifyDonorRow(toDonorRow(fixture));
  return {
    ...fixture,
    resq: { status: result.status, reason: result.reason, daysRemaining: result.daysRemaining },
  };
});

const json = `${JSON.stringify({ note: "Generated by WEB ADMIN/server/validation/buildValidationSet2.js. Dates are '@-N' = N days before the test date. 'resq' is ResQ's current output, not the expert label.", profiles }, null, 2)}\n`;
writeFileSync(join(here, "validationSet2.json"), json);
console.log(`wrote ${join(here, "validationSet2.json")}`);
if (existsSync(join(appRepo, "pubspec.yaml"))) {
  const target = join(appRepo, "test/fixtures/validation_set2.json");
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, json);
  console.log(`wrote ${target}`);
}
for (const p of profiles) {
  console.log(`${p.id}  ${p.resq.status.padEnd(15)} ${String(p.resq.reason ?? "").padEnd(26)} ${p.resq.daysRemaining ?? ""}  ${p.tests}`);
}
